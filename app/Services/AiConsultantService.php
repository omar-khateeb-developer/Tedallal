2. المنظومة التشغيلية المتكاملة:
- المنيو الرقمي الذكي بالـ QR: تصفح فاخر للصور والأوصاف والمكونات، دعم اللغات، طلب فوري من الطاولة، ميزة «نداء الويتر» و«طلب الحساب» بنقرة زر دون صوت أو تلويح.
- الويتر الذكي (AI Waiter): ذكاء اصطناعي مدمج داخل المنيو يرشح الأطباق المتناسقة للزبائن ويزيد متوسط قيمة الفاتورة (Upselling).
- شاشات المطبخ الفورية (KDS): استقبال الطلبات لحظياً من الطاولة بألوان وتنبيهات صوتية ومؤقت إنجاز، وإلغاء فوضى فواتير الورق وضياع الطلبات.
- الكاشير والورديات وتقارير Z-Report: مطابقة الصندوق، كشف الفواتير الملغاة أو المعدلة، ومنع أي تسريب أو تلاعب نقدي.
- إدارة الفروع المتعددة: يستطيع المالك إدارة كل فروعه من لوحة واحدة مركزية، ومقارنة إيرادات الفروع، وتخصيص أسعار ومخزون كل فرع.

3. التسويق والولاء الذاتي (WhatsApp CRM):
- عجلة الحظ للمكافآت (Wheel of Fortune): ميزة ألعاب تفاعلية تلزم الزبون بإدخال رقم الواتساب للفوز بخصم أو طبق مجاني.
- حماية الأرباح: العجلة مقفلة بذكاء ولا تفتح إلا بعد تأكيد الكاشير لدفع الفاتورة، مما يمنع أي تلاعب أو مشاركة للرابط خارج المطعم.
- بوابة واتساب ذاتية: إرسال رسائل ترويجية وتذكيرات تلقائية بعد 24 ساعة بدون حظر أو تكاليف اشتراكات خارجية شهرية.

4. محاذير صارمة:
- لا تخترع ميزات غير موجودة (مثل: الطيران، التوصيل عبر درونز، دفع بالعملات المشفرة).
- لا تتحدث في مواضيع خارج سياق المطاعم، الضيافة، وتدلّل.
- إذا سأل العميل عن تكلفة الاشتراك المحددة بدقة، اذكر أن الباقات مصممة بحسب حجم المطعم وعدد الطاولات بأسعار تشجيعية، وانصحه بطلب استشارة مجانية أو التواصل المباشر لمعرفة الباقة المناسبة لمطعمه فوراً.
PROMPT;

        $contents = [];
        foreach ($history as $msg) {
            if (!empty($msg['role']) && !empty($msg['content'])) {
                $role = ($msg['role'] === 'user') ? 'user' : 'model';
                $contents[] = [
                    'role' => $role,
                    'parts' => [['text' => (string)$msg['content']]],
                ];
            }
        }

        // إضافة رسالة المستخدم الحالية
        $contents[] = [
            'role' => 'user',
            'parts' => [['text' => $userMessage]],
        ];

        // التأكد من أن التبادل يبدأ بـ user
        while (!empty($contents) && $contents[0]['role'] !== 'user') {
            array_shift($contents);
        }

        $payload = [
            'system_instruction' => [
                'parts' => [['text' => $systemPrompt]],
            ],
            'contents' => $contents,
            'generationConfig' => [
                'temperature' => 0.65,
                'topP' => 0.95,
                'maxOutputTokens' => 750,
            ],
        ];

        $endpoint = "https://generativelanguage.googleapis.com/v1beta/models/{$model}:generateContent?key={$apiKey}";

        $res = Http::timeout(10)->post($endpoint, $payload);

        if (!$res->successful()) {
            throw new \RuntimeException('Gemini API returned status ' . $res->status() . ': ' . $res->body());
        }

        $data = $res->json();
        $text = $data['candidates'][0]['content']['parts'][0]['text'] ?? '';

        if (empty(trim($text))) {
            throw new \RuntimeException('Empty response from Gemini');
        }

        return [
            'reply' => trim($text),
            'suggested_actions' => $this->generateSuggestedActions($userMessage),
        ];
    }

