            $reply = "من أهم نقاط قوة «تَدلّل» أنك **لن تحتاج لشراء أجهزة كاشير مخصصة ومكلفة** بملايين الليرات!\n\n- **المنظومة سحابية بالكامل:** تعمل عبر المتصفح على أي جهاز لديك (كمبيوتر، لابتوب، آيباد، تابلت أندرويد، أو حتى هاتف ذكي).\n- **الطباعة الحرارية:** تدعم المنظومة طابعات الفواتير الحرارية القياسية (ESC/POS) عبر الشبكة المحلية أو البلوتوث مباشرة للمطبخ والصندوق.";
